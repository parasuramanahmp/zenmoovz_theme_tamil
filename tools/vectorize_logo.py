"""Trace public/zenmoovz-portrait logo PNG into vector paths used by the animated loader.
Usage: python3 tools/vectorize_logo.py path/to/zenmoovz_portrait.png
Writes src/data/logoPaths.js and public/zenmoovz-logo.svg"""
import sys, json, cv2, numpy as np

src = sys.argv[1] if len(sys.argv) > 1 else 'zenmoovz_portrait.png'
im = cv2.imread(src, cv2.IMREAD_UNCHANGED)
a = im[:, :, 3]
navy = im[1500, 1800][:3].astype(int)          # a pixel inside the navy square
d = np.abs(im[:, :, :3].astype(int) - navy).sum(axis=2)
mask = ((d < 150) & (a > 128)).astype(np.uint8) * 255
cnts, hier = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
cnts = [(c, hier[0][i][3]) for i, c in enumerate(cnts) if cv2.contourArea(c) > 2000]

# crop box = everything that is drawn; scale so the logo is ~626 units wide
xs, ys, xe, ye = [], [], [], []
for c, _ in cnts:
    x, y, w, h = cv2.boundingRect(c); xs.append(x); ys.append(y); xe.append(x + w); ye.append(y + h)
X0, Y0, X1, Y1 = min(xs), min(ys), max(xe), max(ye); S = 0.2
W, H = round((X1 - X0) * S, 1), round((Y1 - Y0) * S, 1)
tx = lambda p: ((p[0] - X0) * S, (p[1] - Y0) * S)

def path(c, eps=1.2):
    pts = cv2.approxPolyDP(c, eps, True)[:, 0, :]
    return 'M' + 'L'.join('%.1f %.1f' % tx(p) for p in pts) + 'Z'

top = [(i, c) for i, (c, p) in enumerate(cnts) if p == -1]
square_i = max(top, key=lambda t: cv2.contourArea(t[1]))[0]
square = path(cnts[square_i][0], 1.2)
holes = [(i, c) for i, (c, p) in enumerate(cnts) if p == square_i]
letters_src = sorted([(i, c) for i, c in top if i != square_i], key=lambda t: cv2.boundingRect(t[1])[0])

ball = None; pieces = {}
for i, c in holes:
    x, y, w, h = cv2.boundingRect(c)
    fill = cv2.contourArea(c) / (w * h)                       # a circle fills ~78.5% of its bounding box
    if abs(w - h) < 10 and .74 < fill < .83:                         # the ball
        (cx, cy), r = cv2.minEnclosingCircle(c); cx, cy = tx((cx, cy)); ball = dict(cx=round(cx, 1), cy=round(cy, 1), r=round(r * S, 1))
    elif w * h < 100000 and cv2.contourArea(c) < 8000:        # thin stripes
        pieces.setdefault('stripes', []).append(path(c, 1))
    else:
        pieces[f'p{i}'] = [path(c)]
# name the pieces by position: top-left, top-right, bottom-left, bottom-right
named = {}
def cy_of(k): 
    c = [cc for ii, cc in holes if f'p{ii}' == k][0]; x, y, w, h = cv2.boundingRect(c); return y, x
order = sorted([k for k in pieces if k != 'stripes'], key=cy_of)
top2 = sorted(order[:2], key=lambda k: cy_of(k)[1]); bot2 = sorted(order[2:], key=lambda k: cy_of(k)[1])
named['topLeft'], named['topMid'], named['bottomLeft'] = pieces[top2[0]], pieces[top2[1]], pieces[bot2[0]]
named['bottomRight'] = pieces[bot2[1]] + pieces.get('stripes', [])

letters = []
for i, c in letters_src:
    ds = [path(c)] + [path(cc) for j, (cc, p) in enumerate(cnts) if p == i]
    letters.append(' '.join(ds))

data = dict(navy='#%02x%02x%02x' % (navy[2], navy[1], navy[0]), width=W, height=H, square=square,
            pieces={k: ' '.join(v) for k, v in named.items()}, ball=ball, letters=letters)
open('src/data/logoPaths.js', 'w').write('/* Generated by tools/vectorize_logo.py from the Zenmoovz portrait logo. Do not edit by hand. */\nexport const LOGO = ' + json.dumps(data, indent=1) + ';\n')

svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" role="img" aria-label="Zenmoovz">', f'<path d="{square}" fill="{data["navy"]}"/>']
svg += [f'<path d="{v}" fill="#fff" fill-rule="evenodd"/>' for v in data['pieces'].values()]
svg += [f'<circle cx="{ball["cx"]}" cy="{ball["cy"]}" r="{ball["r"]}" fill="#fff"/>']
svg += [f'<path d="{l}" fill="{data["navy"]}" fill-rule="evenodd"/>' for l in letters] + ['</svg>']
open('public/zenmoovz-logo.svg', 'w').write('\n'.join(svg))
print('viewBox', W, H, '| pieces', list(named), '| letters', len(letters), '| ball', ball)
